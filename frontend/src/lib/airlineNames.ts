/** يُعيد الاسم العربي لشركة الطيران إن كان معروفاً، وإلا الاسم الأصلي كما وصل من مزوّد البيانات. */
export function getAirlineDisplayName(airlineCode: string, fallbackName: string): string {
  return AIRLINE_NAMES_AR[airlineCode.toUpperCase()] ?? fallbackName;
}
